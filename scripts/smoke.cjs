// Runs the actual renderer in an offscreen Electron window; no server involved.
const {app,BrowserWindow,ipcMain}=require('electron');
const path=require('node:path');
const fs=require('node:fs');
app.commandLine.appendSwitch('ozone-platform','headless');
app.commandLine.appendSwitch('disable-gpu');
app.commandLine.appendSwitch('no-sandbox');
const errors=[];
app.whenReady().then(async()=>{
  const win=new BrowserWindow({width:1500,height:960,show:true,webPreferences:{offscreen:true,preload:path.join(__dirname,'../electron/preload.cjs'),contextIsolation:true,nodeIntegration:false,sandbox:true}});
  win.setContentSize(1500,960);
  let painted=null;win.webContents.on('paint',(_,__,image)=>{if(image.getSize().width>100)painted=image;});
  ipcMain.handle('project:recent',()=>[]);
  let creatorOpened=false;ipcMain.handle('app:open-creator',()=>{creatorOpened=true;});
  win.webContents.on('console-message',(...args)=>{const details=typeof args[1]==='object'?args[1]:null;if(details?.level==='error')errors.push(details.message);});
  win.webContents.on('render-process-gone',(_,details)=>{console.error('Renderer died',details);app.exit(1);});
  await win.loadFile(path.join(__dirname,'../src/index.html'));
  await new Promise(r=>setTimeout(r,1500));
  const result=await win.webContents.executeJavaScript(`(async()=>{
    const t=window.__repoMapTest;
    const assert=(v,m)=>{if(!v)throw new Error(m);};
    assert(t.state.graph.nodes.length>100,'demo graph');
    assert(t.universe.dust.length>2500,'point cloud');
    const count=document.getElementById('statFiles').textContent;
    assert(count==='27','file statistics');
    document.getElementById('search').value='Engine';
    document.getElementById('search').dispatchEvent(new Event('input'));
    assert(document.querySelectorAll('.tree-row').length>0,'search');
    t.select('src/core/Engine.ts',true);
    assert(document.querySelector('.node-title').textContent==='Engine.ts','inspector selection');
    assert(t.universe.related.size>4,'dependency edges');
    [...document.querySelectorAll('.inspector-tabs button')][1].click();
    assert(document.querySelector('.code-preview').textContent.includes('class Engine'),'code preview');
    document.querySelector('[data-layout="clusters"]').click();
    assert(t.universe.layout==='clusters','cluster layout');
    document.getElementById('zoomIn').click();assert(t.universe.zoom>1,'zoom');
    document.getElementById('resetView').click();assert(t.universe.zoom===1,'reset');
    assert(!document.body.textContent.includes('LOCAL / OFFLINE'),'removed header badge');
    document.getElementById('openHelp').click();assert(document.getElementById('helpDialog').open,'help');
    assert(document.getElementById('helpDialog').textContent.includes('/home/whydoyousee'),'creator credit');
    assert(document.getElementById('creatorGithub').href==='https://github.com/whydoyouseegit','creator URL');
    document.getElementById('creatorGithub').click();
    await new Promise(r=>setTimeout(r,50));
    document.getElementById('helpDialog').close();
    document.getElementById('cloneBtn').click();assert(document.getElementById('gitDialog').open,'git dialog');document.getElementById('gitDialog').close();
    document.getElementById('search').value='';document.getElementById('search').dispatchEvent(new Event('input'));
    document.getElementById('clearSelection').click();
    document.querySelector('[data-layout="universe"]').click();
    t.universe.play=false;
    return {nodes:t.state.graph.nodes.length,particles:t.universe.dust.length,files:count,groups:t.universe.groups.length,viewport:[innerWidth,innerHeight]};
  })()`);
  await new Promise(r=>setTimeout(r,700));
  win.webContents.invalidate();
  await new Promise(r=>setTimeout(r,500));
  const image=painted||await win.webContents.capturePage({x:0,y:0,width:1500,height:960});
  fs.writeFileSync(path.join(__dirname,'../../repo-map-ui-qa.png'),image.toPNG());
  if(!creatorOpened)errors.push('Creator GitHub handler was not invoked');
  console.log(JSON.stringify({result,creatorOpened,imageSize:image.getSize(),bounds:win.getBounds(),errors}));
  app.exit(errors.length?1:0);
}).catch(e=>{console.error(e);app.exit(1);});
setTimeout(()=>{console.error('Smoke test timed out');app.exit(1);},30000);
